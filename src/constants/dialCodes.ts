const DEFAULT_DIAL_CODE = '+60';

/** Splits a stored E.164-ish phone string (e.g. "+60123456789") into the
 * dial code + local number `PhoneInputField` edits separately. Matches
 * the *longest* known code first (`+1` is a prefix of nothing else here,
 * but this stays correct if a code sharing a prefix is ever added) and
 * falls back to the default dial code with the whole string as the local
 * number if nothing matches (e.g. a legacy value with no leading `+`). */
const splitPhoneNumber = (
  full: string | null | undefined,
): { dialCode: string; number: string } => {
  const value = (full ?? '').trim();
  if (!value) return { dialCode: DEFAULT_DIAL_CODE, number: '' };

  const match = [...DIAL_CODES]
    .sort((a, b) => b.code.length - a.code.length)
    .find((d) => value.startsWith(d.code));

  if (!match) return { dialCode: DEFAULT_DIAL_CODE, number: value };
  return {
    dialCode: match.code,
    number: value.slice(match.code.length).trim(),
  };
};

/** Inverse of splitPhoneNumber — joins a dial code + local number back
 * into the single string the backend's `phone_number` field stores.
 * Returns '' (not just the bare dial code) when the local number is
 * empty, so an untouched/cleared field submits as genuinely blank. */
const joinPhoneNumber = (dialCode: string, number: string): string => {
  const trimmed = number.trim();
  return trimmed ? `${dialCode}${trimmed}` : '';
};

